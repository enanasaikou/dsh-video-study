import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

export async function buildClient({ write = true } = {}) {
  const vendorUrl = new URL('./vendor/qrcode-generator-1.4.4.js', import.meta.url);
  const bytes = await readFile(vendorUrl);
  if (bytes.length !== 56694 || createHash('sha256').update(bytes).digest('base64') !== 'GK45n4EYK8nekW6cd7GV3yDMWNby1VpisIWimfG/F4A=')
    throw new Error('Pinned QR source integrity mismatch');
  const license = await readFile(new URL('./vendor/LICENSE.qrcode-generator', import.meta.url), 'utf8');
  const source = await readFile(new URL('./source.js', import.meta.url), 'utf8');
  const asrSource = await readFile(new URL('./asr.js', import.meta.url), 'utf8');
  const output = `/* Generated by client/build.mjs; do not edit.\n${license.replaceAll('*/', '* /')}*/\n`
    + `window.__ModuleLoader__.load({id:'dsh-video-study',factory:function(require){\n'use strict';\n`
    + `var React=require('react');\nvar qrcode=(function(){var module={exports:{}};var exports=module.exports;var define;\n`
    + bytes.toString('utf8') + `\nreturn module.exports;})();\n`
    + asrSource + '\n' + source + `\nreturn createVideoStudyClient(React,qrcode);\n}});\n`;
  if (write) await writeFile(new URL('../lib/client.js', import.meta.url), output, 'utf8');
  return output;
}
if (process.argv[1] && new URL('file:' + process.argv[1].replaceAll('\\', '/')).pathname.endsWith('/build.mjs')) {
  await buildClient();
  console.log('Built local ModuleLoader client with verified MIT QR source.');
}
